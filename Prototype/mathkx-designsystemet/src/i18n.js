import { nb2, en2 } from './i18n-iteration2.js';

function deepMerge(a, b) {
  const out = { ...a };
  for (const [k, v] of Object.entries(b)) out[k] = v && typeof v === 'object' && !Array.isArray(v) && typeof a[k] === 'object' ? deepMerge(a[k], v) : v;
  return out;
}

export const DICT = { nb: deepMerge(nb, nb2), en: deepMerge(en, en2) };

export function translate(lang, key, params) {
  const parts = key.split('.');
  let v = DICT[lang];
  for (const p of parts) v = v?.[p];
  if (v == null) {
    v = DICT.nb;
    for (const p of parts) v = v?.[p];
  }
  if (typeof v !== 'string') return key;
  return params ? v.replace(/\{(\w+)\}/g, (_, k) => (params[k] ?? `{${k}}`)) : v;
}

/** Pick a localized value from a {nb, en} object, or return a plain value. */
export function pick(lang, v) {
  if (v && typeof v === 'object' && ('nb' in v || 'en' in v)) return v[lang] ?? v.nb;
  return v;
}
